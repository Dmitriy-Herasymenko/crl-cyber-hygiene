// Скільки питань з кожного курсу (у тому ж порядку, що й courses) потрапляє
// у фінальний тест. Сума = 10.
const FINAL_TEST_COUNTS_PER_COURSE = [3, 3, 2, 2];

export function pickFinalTestQuestions(): QuizQuestion[] {
  const picked = courses.flatMap((course, i) => {
    const shuffled = shuffleArray(course.quiz);
    return shuffled.slice(0, FINAL_TEST_COUNTS_PER_COURSE[i] ?? 0);
  });
  return shuffleArray(picked);
}
